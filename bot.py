user_data = {}

def save_to_excel(data, score, subject, grade):

    file_name = "results.xlsx"

    if not os.path.exists(file_name):

        wb = Workbook()
        ws = wb.active

        headers = [
            "ФИО",
            "Предмет",
            "Класс",
            "Дата и время"
        ] + [f"В{i}" for i in range(1,11)] + ["Балл"]

        ws.append(headers)

        wb.save(file_name)

    wb = load_workbook(file_name)
    ws = wb.active

    current_time = datetime.now().strftime("%d.%m.%Y %H:%M")

    row = [
        data[0][0],
        subject,
        grade,
        current_time
    ]

    for ans in data:
        row.append("✔" if ans[4] else "❌")

    row.append(score)

    ws.append(row)

    wb.save(file_name)

async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):

    user_id = update.message.chat_id

    user_data[user_id] = {
        "name": None,
        "subject": None,
        "grade": None,
        "score": 0,
        "q": 0,
        "answers": [],
        "questions": [],
        "results_mode": False
    }

    keyboard = [[s] for s in subjects.keys()]

    await update.message.reply_text(
        "Добро пожаловать!\n\nВыберите предмет:",
        reply_markup=ReplyKeyboardMarkup(
            keyboard,
            resize_keyboard=True
        )
    )

async def send_results(update: Update,
                       context: ContextTypes.DEFAULT_TYPE):

    if update.message.chat_id != ADMIN_ID:

        await update.message.reply_text(
            "Нет доступа"
        )

        return

    with open("results.xlsx", "rb") as file:

        await update.message.reply_document(
            document=InputFile(file)
        )

async def handle_message(update: Update,
                         context: ContextTypes.DEFAULT_TYPE):

    user_id = update.message.chat_id
    text = update.message.text

    if user_id not in user_data:
        await start(update, context)
        return

    data = user_data[user_id]

    if data["subject"] is None:

        if text in subjects:

            data["subject"] = text

            keyboard = [[g] for g in subjects[text]]

            await update.message.reply_text(
                "Выберите класс:",
                reply_markup=ReplyKeyboardMarkup(
                    keyboard,
                    resize_keyboard=True
                )
            )

            return

    if data["grade"] is None:

        if text in subjects[data["subject"]]:

            data["grade"] = text

            await update.message.reply_text(
                "Введите ваше ФИО:"
            )

            return

    if data["name"] is None:

        data["name"] = text

        all_questions = question_bank[
            data["subject"]
        ][
            data["grade"]
        ]

        data["questions"] = random.sample(
            all_questions,
            10
        )

        await send_question(update, context)

        return

    q_index = data["q"]

    if q_index < len(data["questions"]):

        q = data["questions"][q_index]

        correct = q["answer"]

        is_correct = text == correct

        if is_correct:
            data["score"] += 1

        data["answers"].append([
            data["name"],
            q["question"],
            text,
            correct,
            is_correct
        ])

        data["q"] += 1

        await send_question(update, context)

async def send_question(update: Update,
                        context: ContextTypes.DEFAULT_TYPE):

    user_id = update.message.chat_id

    data = user_data[user_id]

    q_index = data["q"]

    if q_index < len(data["questions"]):

        q = data["questions"][q_index]

        keyboard = [[opt] for opt in q["options"]]

        await update.message.reply_text(
            q["question"],
            reply_markup=ReplyKeyboardMarkup(
                keyboard,
                resize_keyboard=True
            )
        )

    else:

        await finish_test(update, context)

async def finish_test(update: Update,
                      context: ContextTypes.DEFAULT_TYPE):

    user_id = update.message.chat_id

    data = user_data[user_id]

    save_to_excel(
        data["answers"],
        data["score"],
        data["subject"],
        data["grade"]
    )

    percent = round(data["score"] / 10 * 100)

    await update.message.reply_text(
        f"Тест завершён!\n\n"
        f"Предмет: {data['subject']}\n"
        f"Класс: {data['grade']}\n"
        f"Балл: {data['score']}/10\n"
        f"Процент: {percent}%"
    )

